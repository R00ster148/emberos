#!/usr/bin/env python3
"""Convert a PEM bundle of root CA certificates into a BearSSL trust-anchor table (C header).

usage: mkta.py <bundle.pem> [extra.pem ...] > trust_anchors.h
Needs the 'cryptography' Python package.
"""
import sys, datetime
from cryptography import x509
from cryptography.hazmat.primitives.asymmetric import rsa, ec
from cryptography.hazmat.primitives import serialization

CURVES = {"secp256r1": "BR_EC_secp256r1", "secp384r1": "BR_EC_secp384r1", "secp521r1": "BR_EC_secp521r1"}

def load(paths):
    certs = []
    for p in paths:
        data = open(p, "rb").read()
        for block in data.split(b"-----END CERTIFICATE-----"):
            if b"-----BEGIN CERTIFICATE-----" in block:
                pem = block[block.index(b"-----BEGIN CERTIFICATE-----"):] + b"-----END CERTIFICATE-----\n"
                certs.append(x509.load_pem_x509_certificate(pem))
    return certs

def carr(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
    return "static const unsigned char %s[] = {\n%s\n};\n" % (name, "\n".join(lines))

def main():
    now = datetime.datetime.now(datetime.timezone.utc)
    out, entries, skipped = [], [], 0
    seen = set()
    for cert in load(sys.argv[1:]):
        if cert.not_valid_after_utc < now:
            skipped += 1
            continue
        dn = cert.subject.public_bytes()
        key = cert.public_key()
        n = len(entries)
        if isinstance(key, rsa.RSAPublicKey):
            pn = key.public_numbers()
            mod = pn.n.to_bytes((pn.n.bit_length() + 7) // 8, "big")
            exp = pn.e.to_bytes((pn.e.bit_length() + 7) // 8, "big")
            ident = (dn, mod)
            if ident in seen:
                continue
            seen.add(ident)
            out += [carr("TA%d_DN" % n, dn), carr("TA%d_RSA_N" % n, mod), carr("TA%d_RSA_E" % n, exp)]
            entries.append("\t{ { (unsigned char *)TA%d_DN, sizeof TA%d_DN }, BR_X509_TA_CA,\n"
                           "\t  { BR_KEYTYPE_RSA, { .rsa = { (unsigned char *)TA%d_RSA_N, sizeof TA%d_RSA_N,"
                           " (unsigned char *)TA%d_RSA_E, sizeof TA%d_RSA_E } } } }," % (n, n, n, n, n, n))
        elif isinstance(key, ec.EllipticCurvePublicKey) and key.curve.name in CURVES:
            q = key.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
            ident = (dn, q)
            if ident in seen:
                continue
            seen.add(ident)
            out += [carr("TA%d_DN" % n, dn), carr("TA%d_EC_Q" % n, q)]
            entries.append("\t{ { (unsigned char *)TA%d_DN, sizeof TA%d_DN }, BR_X509_TA_CA,\n"
                           "\t  { BR_KEYTYPE_EC, { .ec = { %s, (unsigned char *)TA%d_EC_Q, sizeof TA%d_EC_Q } } } },"
                           % (n, n, CURVES[key.curve.name], n, n))
        else:
            skipped += 1
            continue
    print("/* Generated by tools/mkta.py from %s - %d trust anchors (%d skipped). Do not edit. */"
          % (", ".join(sys.argv[1:]), len(entries), skipped))
    print("#include \"bearssl.h\"\n")
    print("\n".join(out))
    print("static const br_x509_trust_anchor TAs[%d] = {\n%s\n};\n" % (len(entries), "\n".join(entries)))
    print("#define TAs_NUM %d" % len(entries))

main()
